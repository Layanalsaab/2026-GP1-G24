final Map<String, Path> _pathCache = {};

/// Parses an SVG path string once and caches it.
Path svgPath(String data) =>
    _pathCache.putIfAbsent(data, () => parseSvgPathData(data));

/// An icon from an SVG path string (24 x 24 viewBox), painted with a
/// [CustomPainter] so it can be recoloured and (for outline sets) stroked.
class AppIcon extends StatelessWidget {
  const AppIcon(
    this.path, {
    super.key,
    this.size = 24,
    this.color,
    this.stroke,
    this.extraPaths = const [],
    this.semanticLabel,
  });

  /// Filled icon; the path is painted with `fill`.
  const AppIcon.filled(
    this.path, {
    super.key,
    this.size = 24,
    this.color,
    this.semanticLabel,
  }) : stroke = null,
       extraPaths = const [];

  /// Outline icon with the given stroke width (round caps and joins).
  const AppIcon.outline(
    this.path, {
    super.key,
    this.size = 24,
    this.color,
    this.stroke = 1.8,
    this.extraPaths = const [],
    this.semanticLabel,
  });

  final String path;
  final double size;
  final Color? color;

  /// Stroke width, or null for a filled icon.
  final double? stroke;

  /// More paths drawn with the same paint (e.g. the two-part card share icon).
  final List<String> extraPaths;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {
    final c = color ?? IconTheme.of(context).color ?? Colors.black;
    final icon = SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        painter: _IconPainter(
          paths: [svgPath(path), for (final p in extraPaths) svgPath(p)],
          color: c,
          stroke: stroke,
        ),
      ),
    );
    if (semanticLabel == null) return ExcludeSemantics(child: icon);
    return Semantics(label: semanticLabel, image: true, child: icon);
  }
}

class _IconPainter extends CustomPainter {
  _IconPainter({
    required this.paths,
    required this.color,
    required this.stroke,
  });

  final List<Path> paths;
  final Color color;
  final double? stroke;

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 24, size.height / 24);
    final paint = Paint()..color = color;
    if (stroke != null) {
      paint
        ..style = PaintingStyle.stroke
        ..strokeWidth = stroke!
        ..strokeCap = StrokeCap.round
        ..strokeJoin = StrokeJoin.round;
    }
    for (final p in paths) {
      canvas.drawPath(p, paint);
    }
  }

  @override
  bool shouldRepaint(_IconPainter old) =>
      old.color != color || old.stroke != stroke || old.paths != paths;
}
